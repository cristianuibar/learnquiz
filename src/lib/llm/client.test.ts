it('starts a practice session with items and self-checks generated by two different Meta models', async () => {
  Object.assign(getEnv(), { JOB_MODELS: { self_check: { provider: 'meta', model: 'muse-wonder-1.0' } } })
  raw.exec(`
    INSERT INTO topics (id, learner_id, title, status, created_at) VALUES ('t1', 'u1', 'Algebra', 'ready', 1);
    INSERT INTO learner_topic (learner_id, topic_id) VALUES ('u1', 't1');
    INSERT INTO units (id, topic_id, "order", name) VALUES ('un1', 't1', 0, 'Basics');
    INSERT INTO learner_unit (learner_id, unit_id, unlocked_at) VALUES ('u1', 'un1', 1);
    INSERT INTO concepts (id, topic_id, unit_id, "order", name, summary) VALUES ('c1', 't1', 'un1', 0, 'Variables', '');
  `)
  const item = {
    format: 'cloze', stem: 'x + 1 = 2; x = ____', options: [], accepted_answers: ['1'], model_answer: '1',
    explanation: 'Subtract one.', difficulty: 3, source_quote: null, grounded: false, bloom: 'apply',
  }
  const usage = { prompt_tokens: 1000, completion_tokens: 200, completion_tokens_details: { reasoning_tokens: 50 } }
  const fetchModel = vi.fn()
    .mockResolvedValueOnce(Response.json({ usage, choices: [{ message: { content: JSON.stringify({ items: [item, item, item] }) } }] }))
    .mockResolvedValueOnce(Response.json({ usage, choices: [{ message: { content: JSON.stringify({ results: [0, 1, 2].map((index) => ({ index, keep: true, reasons: [] })) }) } }] }))
  vi.stubGlobal('fetch', fetchModel)

  const { sessionId } = await startSession({ data: { topicId: 't1' } })
  expect(raw.prepare('SELECT learner_id, topic_id, kind FROM sessions WHERE id = ?').get(sessionId)).toEqual({ learner_id: 'u1', topic_id: 't1', kind: 'session' })
  const session = await getSession({ data: { sessionId } })
  expect(session.item?.stem).toBe(item.stem)
  expect(fetchModel.mock.calls.map(([, init]) => JSON.parse(init.body).model)).toEqual(['muse-spark-1.3', 'muse-wonder-1.0'])
  expect(raw.prepare('SELECT learner_id, purpose, model, cost_usd, reasoning_tokens, ok FROM model_calls ORDER BY rowid').all()).toEqual([
    { learner_id: 'u1', purpose: 'items', model: 'muse-spark-1.3', cost_usd: 0.0021, reasoning_tokens: 50, ok: 1 },
    { learner_id: 'u1', purpose: 'self_check', model: 'muse-wonder-1.0', cost_usd: null, reasoning_tokens: 50, ok: 1 },
  ])
  expect(raw.prepare('SELECT SUM(cost_usd) AS charged FROM model_calls').get()).toEqual({ charged: 0.0021 })
})

it.each([
  { provider: 'baseten', model: 'muse-spark-open', url: 'https://inference.baseten.co/v1/chat/completions', keyBinding: 'BASETEN_API_KEY' },
  { provider: 'fireworks', model: 'accounts/fireworks/models/muse-spark-open', url: 'https://api.fireworks.ai/inference/v1/chat/completions', keyBinding: 'FIREWORKS_API_KEY' },
])('routes session jobs through $provider and validates the JSON fallback before logging success', async ({ provider, model, url, keyBinding }) => {
  Object.assign(getEnv(), {
    JOB_MODELS: {
      items: { provider: 'meta', model: 'muse-spark-1.3' },
      self_check: { provider, model },
    },
    [keyBinding]: 'provider-key',
  })
  const fetchModel = vi.fn()
    .mockResolvedValueOnce(Response.json({ choices: [{ message: { content: '{"answer":"draft"}' } }] }))
    .mockResolvedValueOnce(Response.json({ choices: [{ message: { content: '{"answer":3}' } }] }))
    .mockResolvedValueOnce(Response.json({ choices: [{ message: { content: '{"answer":"checked"}' } }] }))
  vi.stubGlobal('fetch', fetchModel)

  await expect(chatJson({ ...answerRequest, purpose: 'items' })).resolves.toEqual({ answer: 'draft' })
  await expect(chatJson({ ...answerRequest, purpose: 'self_check' })).resolves.toEqual({ answer: 'checked' })

  const requests = fetchModel.mock.calls.map(([endpoint, init]) => ({ endpoint, headers: init.headers, body: JSON.parse(init.body) }))
  expect(requests.map((r) => [r.endpoint, r.body.model])).toEqual([
    ['https://llm.example/chat/completions', 'muse-spark-1.3'],
    [url, model],
    [url, model],
  ])
  expect(requests[0].body.response_format).toMatchObject({ type: 'json_schema', json_schema: { strict: true, name: 'answer' } })
  expect(requests[0].body.reasoning_effort).toBe('minimal')
  for (const request of requests.slice(1)) {
    expect(request.headers.authorization).toBe('Bearer provider-key')
    expect(request.body.response_format).toEqual({ type: 'json_object' })
    expect(request.body.reasoning_effort).toBeUndefined()
    const schema = request.body.messages[0].content.split('JSON Schema:\n')[1]
    expect(JSON.parse(schema)).toMatchObject({ type: 'object', properties: { answer: { type: 'string' } }, required: ['answer'] })
  }
  expect(requests[2].body.messages.at(-1).content).toContain('Your reply was rejected:')
  expect(raw.prepare('SELECT session_id, purpose, model, ok FROM model_calls ORDER BY rowid').all()).toEqual([
    { session_id: 's1', purpose: 'items', model: 'muse-spark-1.3', ok: 1 },
    { session_id: 's1', purpose: 'self_check', model, ok: 0 },
    { session_id: 's1', purpose: 'self_check', model, ok: 1 },
  ])
})

