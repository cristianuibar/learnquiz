const summary: SummaryView = {
  sessionId: 's1', topicId: 't1', kind: 'session', durationMs: 1000,
  correct: 1, total: 2, ungraded: 0, xp: 10, streak: 0, level: null,
  levelLine: null, levelLineModel: null, endedEarly: false,
  masteryMoved: [], mistakes: [], benchmark: null, reviewsLeft: 0, nextLine: '',
}
const mistake = (generatedBy: string | null): SummaryView['mistakes'][number] => ({
  itemId: 'i1', conceptName: 'Receiving', stem: 'Which dock takes returns?', correctAnswer: 'Dock 4', wasSure: false, generatedBy,
})

function topicPath(generatedBy: string | null, preparing = false, models?: string[]): TopicPath {
  return {
    topic: { id: 't1', title: 'Warehouse picker', goal: null, status: preparing ? 'generating' : 'ready', generatedBy },
    ...(models && { models }),
    preparing, placeable: true, company: null, benchmark: 0.85, edges: [], onboarding: null, mastery: 0.4, nextUnitId: 'u1',
    learner: { level: 3, levelLine: null, levelLineModel: null, placed: true, xp: 0, streak: 0 },
    units: preparing ? [] : [{
      id: 'u1', order: 0, name: 'Receiving', summary: '', mastery: 0.4, measured: true, unlocked: true,
      state: 'learning', criticalCount: 0, canPractice: true, source: null, concepts: [],
    }],
  }
}

const generated = /^Generated by/

describe('Summary', () => {
  it('names the Muse model behind the missed questions', async () => {
    jest.mocked(api).mockResolvedValue({ ...summary, mistakes: [mistake('accounts/fireworks/models/muse-spark-1.3')] })
    await render(h(ThemeProvider, { children: h(SessionDone) }))
    expect(await screen.findByText('Generated by Muse Spark')).toBeOnTheScreen()
  })

  it('names the model that wrote a placement level line', async () => {
    jest.mocked(api).mockResolvedValue({
      ...summary, kind: 'placement', level: 3, levelLine: 'You know the basics.', levelLineModel: 'muse-wonder-1.0',
    })
    await render(h(ThemeProvider, { children: h(SessionDone) }))
    expect(await screen.findByText('Generated by Muse Wonder')).toBeOnTheScreen()
  })

  it('names the session models after a perfect session', async () => {
    jest.mocked(api).mockResolvedValue({ ...summary, correct: 2, mistakes: [], models: ['muse-wonder-1.0', 'muse-spark-1.3'] })
    await render(h(ThemeProvider, { children: h(SessionDone) }))
    expect(await screen.findByText('Generated by Muse Wonder and Muse Spark')).toBeOnTheScreen()
  })

  it('shows no attribution when the payload names no Muse model', async () => {
    jest.mocked(api).mockResolvedValue({ ...summary, mistakes: [mistake(null), mistake('gpt-4o')] })
    await render(h(ThemeProvider, { children: h(SessionDone) }))
    expect(await screen.findByRole('header', { name: 'Session done' })).toBeOnTheScreen()
    expect(screen.queryByText(generated)).toBeNull()
  })
})

describe('Path', () => {
  const show = (path: TopicPath) => {
    jest.mocked(useTopicPath).mockReturnValue({ path, status: 'ready', owner: 'token', retry: jest.fn() })
    return render(h(ThemeProvider, { children: h(PathScreen) }))
  }

  it('names the Muse model behind the curriculum', async () => {
    await show(topicPath('muse-spark-1.3'))
    expect(screen.getByLabelText(/^Unit 1, Receiving/)).toBeOnTheScreen()
    expect(screen.getByText('Generated by Muse Spark')).toBeOnTheScreen()
  })

  it('names the models behind the questions and diagrams too', async () => {
    await show(topicPath('muse-spark-1.3', false, ['muse-spark-1.3', 'muse-image-1.0']))
    expect(screen.getByText('Generated by Muse Spark and Muse Image')).toBeOnTheScreen()
  })

  it('shows no attribution when the topic names no Muse model', async () => {
    await show(topicPath(null))
    expect(screen.getByLabelText(/^Unit 1, Receiving/)).toBeOnTheScreen()
    expect(screen.queryByText(generated)).toBeNull()
  })

  it('shows no attribution while the path is being prepared', async () => {
    await show(topicPath('muse-spark-1.3', true))
    expect(screen.queryByText(generated)).toBeNull()
  })
})
