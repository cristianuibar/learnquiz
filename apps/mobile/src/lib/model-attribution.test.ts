import type { SummaryView } from '@learnquiz/api'
import type { TopicPath } from '@learnquiz/api/progress'
import { pathAttribution, summaryAttribution } from './model-attribution'

type Mistake = SummaryView['mistakes'][number]
const mistake = (itemId: string, generatedBy: string | null): Mistake => ({
  itemId, conceptName: 'Receiving', stem: 'Stem', correctAnswer: 'A', wasSure: false, generatedBy,
})
const summary = (over: Partial<SummaryView>): Pick<SummaryView, 'kind' | 'level' | 'levelLine' | 'levelLineModel' | 'mistakes'> => ({
  kind: 'session', level: null, levelLine: null, levelLineModel: null, mistakes: [], ...over,
})

describe('summaryAttribution', () => {
  it('names the models that wrote the missed questions', () => {
    expect(summaryAttribution(summary({ mistakes: [mistake('i1', 'muse-spark-1.3'), mistake('i2', 'accounts/fireworks/models/muse-spark-1.3')] })))
      .toBe('Generated by Muse Spark')
  })

  it('adds the model that wrote the placement level line', () => {
    expect(summaryAttribution(summary({
      kind: 'placement', level: 3, levelLine: 'You know the basics.', levelLineModel: 'muse-wonder-1.0',
      mistakes: [mistake('i1', 'muse-spark-1.3')],
    }))).toBe('Generated by Muse Wonder and Muse Spark')
  })

  it('ignores a level-line model when no level line is shown', () => {
    expect(summaryAttribution(summary({ kind: 'placement', level: 3, levelLine: null, levelLineModel: 'muse-wonder-1.0' }))).toBeNull()
    expect(summaryAttribution(summary({ kind: 'session', level: 3, levelLine: 'Line', levelLineModel: 'muse-wonder-1.0' }))).toBeNull()
  })

  it('is null when the payload names no Muse model', () => {
    expect(summaryAttribution(summary({}))).toBeNull()
    expect(summaryAttribution(summary({ mistakes: [mistake('i1', null), mistake('i2', 'gpt-4o')] }))).toBeNull()
  })
})

describe('pathAttribution', () => {
  const path = (generatedBy: string | null): Pick<TopicPath, 'topic'> => ({
    topic: { id: 't1', title: 'Picker', goal: null, status: 'ready', generatedBy },
  })

  it('names the model that wrote the curriculum', () => {
    expect(pathAttribution(path('muse-spark-1.3'))).toBe('Generated by Muse Spark')
    expect(pathAttribution(path('muse-spark-open'))).toBe('Generated by Muse Spark Open')
  })

  it('is null when the topic names no Muse model', () => {
    expect(pathAttribution(path(null))).toBeNull()
    expect(pathAttribution(path('gpt-4o'))).toBeNull()
  })
})
