import { describe, expect, it } from 'vitest'
import { generatedByLine, modelDisplayName, museModelName } from './models.ts'

describe('museModelName', () => {
  it.each([
    ['muse-spark-1.3', 'Muse Spark'],
    ['muse-spark-open', 'Muse Spark Open'],
    ['muse-wonder-1.0', 'Muse Wonder'],
    ['muse-image-1.0', 'Muse Image'],
    ['muse-voice-transcribe-1.0', 'Muse Voice Transcribe'],
    ['muse-glimmer', 'Muse Glimmer'],
    ['accounts/fireworks/models/muse-spark-1.3', 'Muse Spark'],
  ])('names %s as %s', (id, name) => {
    expect(museModelName(id)).toBe(name)
  })

  it.each([null, undefined, '', 'gpt-4o', 'llama-3.1-8b', 'accounts/fireworks/models/llama-v3', 'toString', 'constructor'])('names nothing for %s', (id) => {
    expect(museModelName(id)).toBeNull()
  })
})

describe('modelDisplayName', () => {
  it('shows an unknown id as recorded', () => {
    expect(modelDisplayName('muse-wonder-1.0')).toBe('Muse Wonder')
    expect(modelDisplayName('custom-model')).toBe('custom-model')
  })
})

describe('generatedByLine', () => {
  it('names one model', () => {
    expect(generatedByLine(['muse-spark-1.3'])).toBe('Generated by Muse Spark')
  })

  it('lists each Muse model once in first-seen order', () => {
    expect(generatedByLine(['muse-wonder-1.0', 'accounts/fireworks/models/muse-spark-1.3', 'muse-wonder-1.0'])).toBe('Generated by Muse Wonder and Muse Spark')
    expect(generatedByLine(['muse-spark-1.3', 'muse-wonder-1.0', 'muse-glimmer'])).toBe('Generated by Muse Spark, Muse Wonder and Muse Glimmer')
  })

  it('never names a model that is not a Muse model', () => {
    expect(generatedByLine(['gpt-4o', 'muse-glimmer', null])).toBe('Generated by Muse Glimmer')
  })

  it('is null when no Muse model is named', () => {
    expect(generatedByLine([])).toBeNull()
    expect(generatedByLine([null, undefined, 'gpt-4o'])).toBeNull()
  })
})
