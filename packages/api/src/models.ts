// Display names for the Meta models LearnQuiz records, shared by the web and
// mobile apps. Fireworks may prefix the exact Meta ids with accounts/fireworks/models/.
const FIREWORKS_PREFIX = 'accounts/fireworks/models/'

const MODEL_NAMES = new Map<string, string>([
  ['muse-spark-1.3', 'Muse Spark'],
  ['muse-spark-open', 'Muse Spark Open'],
  ['muse-glimmer', 'Muse Glimmer'],
  ['muse-wonder-1.0', 'Muse Wonder'],
  ['muse-image-1.0', 'Muse Image'],
  ['muse-voice-transcribe-1.0', 'Muse Voice Transcribe'],
])

function bareId(id: string): string {
  return id.startsWith(FIREWORKS_PREFIX) ? id.slice(FIREWORKS_PREFIX.length) : id
}

// The Muse name for a recorded model id, or null for any id that is not a known Muse model.
export function museModelName(id: string | null | undefined): string | null {
  if (!id) return null
  return MODEL_NAMES.get(bareId(id)) ?? null
}

// Display name for a recorded model id; an unknown id is shown as recorded, never guessed.
export function modelDisplayName(id: string): string {
  return museModelName(id) ?? id
}

// "Generated by Muse Spark", "… by Muse Spark and Muse Wonder", "… by A, B and C".
// Unknown ids are dropped and each name is listed once, in first-seen order;
// null when no Muse model is named.
export function generatedByLine(ids: readonly (string | null | undefined)[]): string | null {
  const names = [...new Set(ids.map(museModelName).filter((name): name is string => name !== null))]
  if (names.length === 0) return null
  const list = names.length === 1 ? names[0] : `${names.slice(0, -1).join(', ')} and ${names[names.length - 1]}`
  return `Generated by ${list}`
}
